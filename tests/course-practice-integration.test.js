const assert=require('node:assert/strict');
const course=require('../course-complete.js');
const content=require('../course-complete-content.js');
const lesson=content.modules.find(m=>m.id==='8').steps.find(s=>s.type==='compose');
assert.deepEqual(content.modules.map(m=>m.id),['3','4','6','8','5','7']);
assert.equal(content.modules.find(m=>m.id==='5').optional,true);
assert(!content.modules.find(m=>m.id==='8').prerequisites.includes('5'));
const note={midi:60,beats:1,str:2,fret:1};
assert.deepEqual(course.withFingering(lesson,note),note,'preserve the chosen unison instead of switching strings');
assert.deepEqual(course.withFingering(lesson,{midi:60,beats:1}),{midi:60,beats:1,str:4,fret:10});
assert.deepEqual(course.withFingering(lesson,{midi:null,beats:1,str:2,fret:1}),{midi:null,beats:1});
assert(!course.validFingering({midi:60,str:5,fret:2}));
const raw={version:1,module:'8',sessions:{'8-project':{events:[note],tempo:55}},done:{}};
const restored=course.cleanState(raw);
assert.deepEqual(restored.sessions['8-project'].events,[note]);
assert.equal(restored.sessions['8-project'].tempo,55);
raw.sessions['8-project'].events=[{midi:60,beats:1,str:5,fret:2}];
assert.deepEqual(course.cleanState(raw).sessions['8-project'].events,[{midi:60,beats:1}]);
assert.equal(course.validatePhrase(lesson,Array.from({length:16},()=>({midi:48,beats:1}))), '','free composition checks structure only; the constrained variation has its own validator');
console.log('OK: retained string/fret, explicit recommended-position fallback, old save compatibility, tempo and optional advanced route');
