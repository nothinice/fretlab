  function rhythmPattern(id,title,labels,pattern,instruction){
    const shapes=[...new Set(labels)].map(label=>({label,frets:[...voicings[label].frets],fingers:[...voicings[label].fingers]}));
    const strokes=labels.flatMap((label,bar)=>pattern.map(([beat,direction])=>({atBeat:bar*4+beat,direction})));
    const backing=strokes.map((stroke,index)=>{
      const label=labels[Math.floor(stroke.atBeat/4)];
      return {atBeat:stroke.atBeat,beats:(strokes[index+1]?.atBeat??8)-stroke.atBeat,label,
        notes:voicings[label].frets.flatMap((fret,index)=>fret===null?[]:[OPEN[index+1]+fret])};
    });
    return {id,title,instruction,events:[{midi:null,beats:4},{midi:null,beats:4}],progression:backing,strokes,voicings:shapes};
  }
