  function validateEar(study,midis,roundIndex=0) {
    const definition=resolveStudy(study),target=definition?.ear?.rounds?.[roundIndex]?.events;
    if (!target || !Number.isInteger(roundIndex)) return 'Выберите слуховое задание.';
    if (!Array.isArray(midis) || midis.some(n => !Number.isInteger(n) || n < 0 || n > 127)) return 'Выберите ноты услышанной фразы.';
    if (midis.length !== target.length) return `В этом рисунке ${target.length} звука. Проверьте количество выбранных нот.`;
    return midis.every((midi,index) => midi === target[index].midi) ? '' : 'Пока не совпало. Пропойте движение и сравните по одному звуку; важны порядок и октава.';
  }
  function validateVariation(study,events) {
    const definition=resolveStudy(study),task=definition?.variation;
    if (!task || !Array.isArray(events)) return 'Выберите упражнение на изменение окончания.';
    const source=task.sourceEvents;
    if (events.length !== source.length) return 'Сохраните восемь событий исходного рисунка: меняется только последнее.';
    for (let i=0;i<events.length;i++) {
      const event=events[i];
      if (!event || !Number.isInteger(event.midi) || !Number.isFinite(event.beats) || !definition.points.some(p => p.midi===event.midi)) return 'Используйте звуки показанной позиции.';
      if (event.str !== undefined || event.fret !== undefined) {
        if (!Number.isInteger(event.str) || !OPEN[event.str] || !Number.isInteger(event.fret) || event.fret<0 || event.fret>16 || OPEN[event.str]+event.fret!==event.midi) return 'Нота и выбранное место на грифе не совпадают.';
      }
      if (event.beats !== source[i].beats) return 'В этом упражнении сохраните ритм: каждое событие длится одну долю.';
      if (i<task.preserveCount && event.midi !== source[i].midi) return 'Верните первые семь нот: сейчас меняется только последнее окончание.';
    }
    const last=events.at(-1).midi;
    if (last===source.at(-1).midi) return 'Окончание пока не изменилось. Выберите другую предложенную опору.';
    return task.allowedLastMidi.includes(last) ? '' : 'Последний звук должен быть одной из предложенных опор нового окончания.';
  }
  return {studies,validateEar,validateVariation};
